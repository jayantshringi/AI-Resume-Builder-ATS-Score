import os
import json
import logging
try:
    import requests
except ImportError:
    requests = None

try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    pass

logger = logging.getLogger(__name__)

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "").strip()
GEMINI_MODEL = os.getenv("GEMINI_MODEL", "gemini-flash-lite-latest").strip()

def _call_gemini(prompt: str, timeout: int = 15) -> tuple[bool, str]:
    if requests is None:
        return False, "The 'requests' package is not installed. Please run: pip install requests"

    api_key = os.getenv("GEMINI_API_KEY", GEMINI_API_KEY).strip()
    if not api_key:
        return False, "Gemini API key is not configured in .env."

    model = os.getenv("GEMINI_MODEL", GEMINI_MODEL).strip() or "gemini-flash-lite-latest"
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"

    payload = {
        "contents": [
            {
                "parts": [
                    {"text": prompt}
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.3,
            "maxOutputTokens": 1000
        }
    }

    try:
        response = requests.post(
            url,
            json=payload,
            headers={"Content-Type": "application/json"},
            timeout=timeout
        )
        if response.status_code == 200:
            data = response.json()
            candidates = data.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return True, parts[0].get("text", "").strip()
            return False, "No response content generated by Gemini."
        
        error_detail = response.json().get("error", {}).get("message", response.text)
        logger.warning(f"Gemini API returned error ({response.status_code}): {error_detail}")
        return False, f"Gemini API Error: {error_detail}"
    except requests.exceptions.Timeout:
        return False, "Gemini request timed out. Please try again."
    except Exception as exc:
        logger.exception("Unexpected error calling Gemini API")
        return False, str(exc)


def improve_bullet_points(text: str, target_role: str = "") -> dict:
    if not text.strip():
        return {"success": False, "result": "", "message": "No text provided to improve."}

    role_context = f" for a {target_role} position" if target_role.strip() else ""
    prompt = f"""You are an elite ATS resume writer and hiring expert.
Rewrite and optimize the following resume experience/project description{role_context}.

Guidelines:
1. Turn informal notes or paragraphs into 2-4 impactful, high-power ATS bullet points.
2. Start each bullet point with a strong, active verb (e.g. Engineered, Spearheaded, Architected, Optimized).
3. Emphasize quantifiable results, technical tools, and business value where plausible.
4. Keep the output clean: return ONLY the bullet points, no conversational preamble or markdown codeblocks.

Original draft:
{text}"""

    ok, result = _call_gemini(prompt)
    if ok:
        return {"success": True, "result": result, "message": "Enhanced successfully with AI."}
    
    # Fallback heuristic if API unavailable
    return {
        "success": False,
        "result": text,
        "message": f"AI unavailable ({result}). Your original text was kept."
    }


def generate_summary(job_title: str, skills: str, experience: str) -> dict:
    title_str = job_title.strip() or "Professional"
    skills_str = skills.strip() or "Core Technical Skills"
    exp_str = experience.strip() or "General work experience"

    prompt = f"""You are an expert executive resume writer.
Write a powerful 2 to 3 sentence Professional Summary for a candidate's resume.

Candidate Details:
- Target Role: {title_str}
- Key Skills: {skills_str}
- Experience / Background: {exp_str}

Guidelines:
- Concise, confident, ATS-optimized language.
- Highlight technical strengths and career focus.
- Return ONLY the summary paragraph without quotes, preamble, or headings."""

    ok, result = _call_gemini(prompt)
    if ok:
        return {"success": True, "result": result, "message": "Summary generated successfully with AI."}

    return {
        "success": False,
        "result": "",
        "message": f"AI unavailable ({result})."
    }


def get_ai_ats_feedback(resume_text: str, job_description: str, missing_keywords: list = None) -> list[str]:
    missing_str = ", ".join(missing_keywords[:8]) if missing_keywords else "general skills"
    prompt = f"""You are an expert ATS recruiter. Compare this candidate resume against the job posting.
Missing or weak keywords detected: {missing_str}

Job Description snippet:
{job_description[:800]}

Candidate Resume snippet:
{resume_text[:1200]}

Provide exactly 3 concise, highly actionable tips on how this candidate can naturally align their real experience with this job without keyword stuffing.
Return as 3 short bullet points, each starting with an action verb."""

    ok, result = _call_gemini(prompt)
    if ok:
        lines = [line.strip().lstrip("*-•123456789. ") for line in result.split("\n") if line.strip()]
        return lines[:3]
    return []
